export function buildMaoCorpusThoughts(
  profileThoughts: Thought[],
  seeds: readonly MaoCorpusSeed[],
): Thought[] {
  const profiles = new Map(profileThoughts.map((thought) => [thought.id, thought]));

  return seeds.map((seed) => {
    const profile = profiles.get(seed.authorId);
    if (!profile) throw new Error(`Missing Mao thought profile: ${seed.authorId}`);

    return applyMaoSourceUpgrade({
      ...profile,
      editorialSummary: undefined,
      englishEditorialSummary: undefined,
      ...seed,
      presentationNature: "editorial-synthesis",
      rendering: "paraphrase",
    });
  });
}

export function buildMaoExpansionThoughts(profileThoughts: Thought[]): Thought[] {
  return buildMaoCorpusThoughts(profileThoughts, maoExpansionSeeds);
}
