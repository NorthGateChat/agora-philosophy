export function buildContemporaryExpansionThoughts(primaryThoughts: Thought[]): Thought[] {
  const profiles = new Map(primaryThoughts.map((thought) => [thought.id, thought]));

  return contemporaryExpansionSeeds.map((seed) => {
    const profile = profiles.get(seed.authorId);
    if (!profile) throw new Error(`Missing primary philosopher profile: ${seed.authorId}`);

    return {
      ...profile,
      ...seed,
      editorialSummary: seed.editorialSummary,
      englishEditorialSummary: seed.englishEditorialSummary,
      presentationNature: seed.presentationNature ?? "editorial-synthesis",
      rendering:
        seed.presentationNature === "source-excerpt"
          ? "short-quote"
          : "paraphrase",
    };
  });
}
