export function buildAncientExpansionThoughts(primaryThoughts: Thought[]): Thought[] {
  const profiles = new Map(primaryThoughts.map((thought) => [thought.id, thought]));

  return ancientExpansionSeeds.map((seed) => {
    const profile = profiles.get(seed.authorId);
    if (!profile) {
      throw new Error(`Missing primary philosopher profile: ${seed.authorId}`);
    }

    const sourceUpgrade = ancientSourceUpgrades[seed.id];
    const presentationNature = sourceUpgrade
      ? "source-excerpt"
      : seed.presentationNature ?? "editorial-synthesis";

    return {
      ...profile,
      ...seed,
      ...sourceUpgrade,
      editorialSummary: sourceUpgrade
        ? seed.editorialSummary ?? seed.text
        : seed.editorialSummary,
      englishEditorialSummary: sourceUpgrade
        ? seed.englishEditorialSummary ?? seed.english
        : seed.englishEditorialSummary,
      presentationNature,
      rendering:
        presentationNature === "source-excerpt"
          ? "short-quote"
          : "paraphrase",
    };
  });
}
