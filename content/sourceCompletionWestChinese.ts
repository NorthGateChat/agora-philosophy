function retain(
  reason: RetainedEditorialReason,
  note: RetainedEditorialSourceDisposition["note"],
  ids: readonly string[],
): RetainedEditorialSourceDisposition[] {
  return ids.map((id) => ({
    id,
    decision: "retain-editorial",
    reason,
    reviewedOn: "2026-08-28",
    note,
  }));
}

